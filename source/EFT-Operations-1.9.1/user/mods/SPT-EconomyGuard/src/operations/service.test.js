'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { OperationsService } = require('./service');

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'eft-ops-'));
const service = new OperationsService(root, { info() {}, warn() {} });
const mission = service.save({ title: 'North Clearance', description: 'Test mission', map: 'woods', mode: 'squad', minPlayers: 2, maxPlayers: 2,
  objectives: [{ id: 'kills', type: 'kill', target: 'scav', count: 2, required: true }, { id: 'extract', type: 'extract', count: 1, required: true }],
  rewards: { points: 1000, roubles: 250000, items: [] } });
assert.equal(mission.status, 'draft');
assert.throws(() => service.setStatus(mission.id, 'closed'), /INVALID_STATUS_TRANSITION/);
service.setStatus(mission.id, 'published');
const g = service.accept(mission.id, 'abcdef0123456789abcdef01', 'Alpha');
service.accept(mission.id, 'abcdef0123456789abcdef02', 'Bravo');
assert.equal(service.setReady(g.id, 'abcdef0123456789abcdef01', true).canStart, false);
assert.equal(service.setReady(g.id, 'abcdef0123456789abcdef02', true).canStart, true);
assert.throws(() => service.startGroup(g.id, ''), /INVALID_RAID_ID/);
service.startGroup(g.id, 'raid-001');
service.recordRaidEvent(g.id, { type: 'kill', target: 'scav', amount: 2 });
service.recordRaidEvent(g.id, { type: 'extract', amount: 1 });
assert.equal(service.finishGroup(g.id, { verified: true, aliveProfileIds: ['abcdef0123456789abcdef01', 'abcdef0123456789abcdef02'], extractedProfileIds: ['abcdef0123456789abcdef01', 'abcdef0123456789abcdef02'] }).state, 'review', 'a bare verified boolean must not authorize automatic rewards');
const done = service.finishGroup(g.id, { verified: true, evidenceTrust: 'server_verified', source: 'fika-server-adapter', aliveProfileIds: ['abcdef0123456789abcdef01', 'abcdef0123456789abcdef02'], extractedProfileIds: ['abcdef0123456789abcdef01', 'abcdef0123456789abcdef02'] });
assert.equal(done.state, 'completed');
assert.equal(service.getPlayer('abcdef0123456789abcdef01').points, 1000);
assert.equal(service.getPlayer('abcdef0123456789abcdef01').rank, 'Private');
assert.equal(service.state.awards.length, 2);
assert.throws(() => service.finishGroup(g.id, { verified: true }), /RAID_NOT_ACTIVE/);
const untrustedMission = service.save({ title: 'Untrusted outcome guard', map: 'woods', mode: 'solo', minPlayers: 1, maxPlayers: 1, objectives: [{ id: 'extract', type: 'extract', count: 1 }], rewards: { points: 999, roubles: 0, items: [] } });
service.setStatus(untrustedMission.id, 'published');
const untrustedGroup = service.accept(untrustedMission.id, 'abcdef0123456789abcdef08', 'Untrusted');
service.setReady(untrustedGroup.id, 'abcdef0123456789abcdef08', true);
service.startGroup(untrustedGroup.id, 'raid-untrusted');
service.recordRaidEvent(untrustedGroup.id, { type: 'extract', amount: 1 });
const untrustedFinish = service.finishGroup(untrustedGroup.id, { verified: true, aliveProfileIds: ['abcdef0123456789abcdef08'], extractedProfileIds: ['abcdef0123456789abcdef08'] });
assert.equal(untrustedFinish.state, 'review', 'a bare verified boolean must not authorize automatic rewards');
assert.equal(service.getPlayer('abcdef0123456789abcdef08').points, 0);
const reloaded = new OperationsService(root, { info() {}, warn() {} }, { ranks: [] });
assert.equal(reloaded.getPlayer('abcdef0123456789abcdef02').completedMissions, 1);
assert.equal(reloaded.state.awards.length, 2);
assert.equal(reloaded.getPlayer('abcdef0123456789abcdef01').rank, 'Private', 'empty configured ranks safely fall back to defaults');
assert.throws(() => reloaded.save({ title: '', map: 'woods', objectives: [] }), /INVALID_TITLE/);
assert.throws(() => reloaded.save({ title: 'Bad date', map: 'woods', objectives: [{ id: 'x', type: 'extract' }], startAt: 'not-a-date' }), /INVALID_START_AT/);
assert.throws(() => reloaded.save({ title: 'Bad window', map: 'woods', objectives: [{ id: 'x', type: 'extract' }], startAt: '2026-01-02T00:00:00Z', endAt: '2026-01-01T00:00:00Z' }), /INVALID_END_AT/);
assert.throws(() => reloaded.save({ title: 'Duplicate objective', map: 'woods', objectives: [{ id: 'x', type: 'extract' }, { id: 'x', type: 'kill' }] }), /INVALID_OBJECTIVE_ID_DUPLICATE/);
assert.throws(() => reloaded.save({ title: 'Bad item reward', map: 'woods', objectives: [{ id: 'x', type: 'extract' }], rewards: { items: [{ tpl: 'bad', count: 1 }] } }), /INVALID_REWARD_TPL/);
const duplicateMission = reloaded.save({ title: 'No duplicate join', map: 'woods', mode: 'either', minPlayers: 1, maxPlayers: 1, objectives: [{ id: 'x', type: 'extract' }] });
assert.throws(() => reloaded.accept(duplicateMission.id, 'not-a-profile-id'), /INVALID_PROFILE_ID/);
reloaded.setStatus(duplicateMission.id, 'published'); const single = reloaded.accept(duplicateMission.id, 'abcdef0123456789abcdef03'); reloaded.setReady(single.id, 'abcdef0123456789abcdef03', true); reloaded.startGroup(single.id, 'raid-C');
assert.throws(() => reloaded.accept(duplicateMission.id, 'abcdef0123456789abcdef03'), /PLAYER_ALREADY_ASSIGNED/);

assert.throws(() => reloaded.save({ title: 'Bad solo', map: 'woods', mode: 'solo', minPlayers: 1, maxPlayers: 2, objectives: [{ id: 'x', type: 'extract' }] }), /INVALID_SOLO_PLAYER_RANGE/);
assert.throws(() => reloaded.save({ title: 'Bad squad', map: 'woods', mode: 'squad', minPlayers: 1, maxPlayers: 4, objectives: [{ id: 'x', type: 'extract' }] }), /INVALID_SQUAD_PLAYER_RANGE/);
const scheduled = reloaded.save({ title: 'Future op', map: 'woods', mode: 'solo', minPlayers: 1, maxPlayers: 1, startAt: new Date(Date.now() + 60000).toISOString(), objectives: [{ id: 'x', type: 'extract' }] });
reloaded.setStatus(scheduled.id, 'published');
assert.throws(() => reloaded.accept(scheduled.id, 'abcdef0123456789abcdef04'), /MISSION_NOT_STARTED/);
const crossMissionA = reloaded.save({ title: 'Single active mission A', map: 'woods', mode: 'solo', minPlayers: 1, maxPlayers: 1, objectives: [{ id: 'x', type: 'extract' }] });
const crossMissionB = reloaded.save({ title: 'Single active mission B', map: 'customs', mode: 'solo', minPlayers: 1, maxPlayers: 1, objectives: [{ id: 'x', type: 'extract' }] });
reloaded.setStatus(crossMissionA.id, 'published'); reloaded.setStatus(crossMissionB.id, 'published');
reloaded.accept(crossMissionA.id, 'abcdef0123456789abcdef07');
assert.throws(() => reloaded.accept(crossMissionB.id, 'abcdef0123456789abcdef07'), /PLAYER_ALREADY_ASSIGNED/);
const reviewMission = reloaded.save({ title: 'Manual review operation', map: 'customs', mode: 'squad', minPlayers: 2, maxPlayers: 2, objectives: [{ id: 'kills', type: 'kill', target: 'scav', count: 1 }, { id: 'extract', type: 'extract', count: 1 }], rewards: { points: 250, roubles: 0, items: [] } });
reloaded.setStatus(reviewMission.id, 'published');
const reviewGroup = reloaded.accept(reviewMission.id, 'abcdef0123456789abcdef05', 'Review One');
reloaded.accept(reviewMission.id, 'abcdef0123456789abcdef06', 'Review Two');
reloaded.setReady(reviewGroup.id, 'abcdef0123456789abcdef05', true);
reloaded.setReady(reviewGroup.id, 'abcdef0123456789abcdef06', true);
reloaded.startGroup(reviewGroup.id, 'raid-review');
reloaded.recordRaidEvent(reviewGroup.id, { type: 'kill', target: 'scav', amount: 1 });
reloaded.recordRaidEvent(reviewGroup.id, { type: 'extract', amount: 1 });
const pendingReview = reloaded.finishGroup(reviewGroup.id, { verified: false, aliveProfileIds: ['abcdef0123456789abcdef05', 'abcdef0123456789abcdef06'], extractedProfileIds: ['abcdef0123456789abcdef05', 'abcdef0123456789abcdef06'] });
assert.equal(pendingReview.state, 'review');
assert.equal(reloaded.reviewQueue().length, 1);
assert.throws(() => reloaded.accept(reviewMission.id, 'abcdef0123456789abcdef05'), /PLAYER_REVIEW_PENDING/);
assert.throws(() => reloaded.resolveReview(reviewGroup.id, 'approve', ''), /INVALID_REVIEW_NOTE/);
assert.throws(() => reloaded.resolveReview(reviewGroup.id, 'approve', 'Verified against server raid log: raid-review'), /REVIEW_ATTESTATION_REQUIRED/);
const reviewed = reloaded.resolveReview(reviewGroup.id, 'approve', 'Verified against server raid log: raid-review', 'ADMIN', { confirmed: true });
assert.equal(reviewed.state, 'completed');
assert.equal(reloaded.getPlayer('abcdef0123456789abcdef05').points, 250);
assert.equal(reloaded.reviewQueue().length, 0);
fs.rmSync(root, { recursive: true, force: true });
console.log('OperationsService: all tests passed');
