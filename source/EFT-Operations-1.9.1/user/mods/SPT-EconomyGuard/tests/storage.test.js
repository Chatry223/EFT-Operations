'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { Storage } = require('../src/storage');

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'eg-storage-'));
const storage = new Storage(temp, { maxFileSizeMb: 0.0005, auditRetentionDays: 60, ledgerRetentionDays: 180, caseRetentionDays: 90 }, { error() {}, warn() {} });
for (let i = 0; i < 24; i++) storage.ledger({ id: i, payload: 'x'.repeat(120) });
const files = fs.readdirSync(path.join(temp, 'ledger')).filter(x => x.endsWith('.jsonl'));
assert.ok(files.length >= 2, 'rotation should create additional part files');
assert.ok(files.length < 24, 'rotation must reuse current part, not create a file for each line');
const loaded = storage.loadRecentLedger(100);
assert.strictEqual(loaded.length, 24, 'rotated ledger parts must all be readable');
const openCase = storage.createCase({ type: 'TEST_OPEN', severity: 'LOW', evidence: { ok: true } });
const closedCase = storage.createCase({ type: 'TEST_CLOSED', severity: 'LOW', evidence: { ok: true } });
const openPath = path.join(temp, 'cases', openCase.caseId + '.json');
const closedPath = path.join(temp, 'cases', closedCase.caseId + '.json');
const closedRecord = JSON.parse(fs.readFileSync(closedPath, 'utf8'));
closedRecord.status = 'CLOSED';
fs.writeFileSync(closedPath, JSON.stringify(closedRecord));
const old = new Date(Date.now() - 120 * 86400000);
fs.utimesSync(openPath, old, old);
fs.utimesSync(closedPath, old, old);
new Storage(temp, { maxFileSizeMb: 0.0005, auditRetentionDays: 60, ledgerRetentionDays: 180, caseRetentionDays: 90 }, { error() {}, warn() {} });
assert.ok(fs.existsSync(openPath), 'OPEN cases must never be removed by retention cleanup');
assert.ok(!fs.existsSync(closedPath), 'old CLOSED cases may be pruned after configured retention');
fs.rmSync(temp, { recursive: true, force: true });
console.log('PASS Storage rotation, ledger reloading and case persistence');
