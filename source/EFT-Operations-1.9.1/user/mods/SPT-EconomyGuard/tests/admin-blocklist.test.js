'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { EconomyGuard } = require('../src/engine');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'eg-blocklist-'));
const profileA = '0123456789abcdef01234567';
const profileB = 'abcdef0123456789abcdef01';
const itemTpl = '5e81f423763d9f754677bf2e';
const guard = new EconomyGuard(__dirname, { enabled:true, mode:'protect', dataDirectory:path.join(root,'data'), restrictions:{enabled:true}, storage:{caseRetentionDays:90}, flea:{maxTrackedEventsInMemory:100} }, {info(){},warn(){},error(){}}, {});
guard.restrictions = { enabled:true, players:{}, items:{} };
let result = guard.checkPlayerPurchasePolicy({_id:profileA}, itemTpl, 1, 'trader-money', 'trader', profileA);
assert.strictEqual(result.valid, true, 'unlisted profile must be unrestricted');
guard.restrictions.players[profileA] = { blocked:true, reason:'manual permanent block', rules:[] };
result = guard.checkPlayerPurchasePolicy({_id:profileA}, itemTpl, 1, 'trader-money', 'trader', profileA);
assert.strictEqual(result.valid, false); assert.strictEqual(result.reason, 'PLAYER_BLOCKLISTED');
guard.restrictions.players[profileA].blocked = false;
guard.restrictions.players[profileA].expiresAt = '2000-01-01T00:00:00.000Z';
result = guard.checkPlayerPurchasePolicy({_id:profileA}, itemTpl, 1, 'trader-money', 'trader', profileA);
assert.strictEqual(result.valid, true, 'expired player suspension must not remain active');
guard.restrictions.players[profileA] = { rules:[] };
guard.restrictions.items[itemTpl] = { blocked:true, channels:['any'], reason:'known buggy custom item' };
result = guard.checkPlayerPurchasePolicy({_id:profileB}, itemTpl, 1, 'flea-money', null, profileB);
assert.strictEqual(result.valid, false); assert.strictEqual(result.reason, 'ITEM_BLOCKLISTED');
result = guard.checkPlayerPurchasePolicy({_id:profileB}, '5f0000000000000000000000', 1, 'flea-money', null, profileB);
assert.strictEqual(result.valid, true, 'global item block must not spill over to other TPLs');
guard.restrictions.items[itemTpl].expiresAt = '2000-01-01T00:00:00.000Z';
result = guard.checkPlayerPurchasePolicy({_id:profileB}, itemTpl, 1, 'flea-money', null, profileB);
assert.strictEqual(result.valid, true, 'expired item block must be inactive');
guard.restrictions.players[profileA] = { rules:[{ ruleId:'r1', tpl:itemTpl, channel:'trader-barter', block:true }] };
result = guard.checkPlayerPurchasePolicy({_id:profileA}, itemTpl, 1, 'trader-barter', 'trader', profileA);
assert.strictEqual(result.valid, false); assert.strictEqual(result.reason, 'PLAYER_TPL_BLOCKED_BY_POLICY');
result = guard.checkPlayerPurchasePolicy({_id:profileA}, itemTpl, 1, 'flea-money', 'trader', profileA);
assert.strictEqual(result.valid, true, 'channel-specific rule must not spill to another channel');
guard.restrictions.players[profileA] = { blocked: true, blockedUntil: '2000-01-01T00:00:00.000Z', rules:[{tpl:itemTpl, channel:'trader-barter', block:true}] };
result = guard.checkPlayerPurchasePolicy({_id:profileA}, itemTpl, 1, 'trader-barter', 'trader', profileA);
assert.strictEqual(result.valid, false, 'expired full suspension must not disable a separate active item rule');

// Item channel scope and timed full-account suspension are isolated correctly.
guard.restrictions.items[itemTpl] = { blocked:true, channels:['trader-money'], reason:'trader only' };
assert.strictEqual(guard.checkPlayerPurchasePolicy({_id:profileB}, itemTpl, 1, 'trader-money', 'trader', profileB).reason, 'ITEM_BLOCKLISTED');
assert.strictEqual(guard.checkPlayerPurchasePolicy({_id:profileB}, itemTpl, 1, 'flea-money', null, profileB).valid, true);
guard.restrictions.players[profileA] = { blocked:true, blockedUntil:new Date(Date.now()+60000).toISOString(), rules:[] };
assert.strictEqual(guard.checkPlayerPurchasePolicy({_id:profileA}, itemTpl, 1, 'flea-money', null, profileA).reason, 'PLAYER_BLOCKLISTED');
guard.restrictions.players[profileA].blockedUntil = new Date(Date.now()-60000).toISOString();
assert.strictEqual(guard.checkPlayerPurchasePolicy({_id:profileA}, itemTpl, 1, 'flea-money', null, profileA).valid, true);

guard.storage.saveRestrictions(guard.restrictions);
const reloaded = guard.storage.loadRestrictions();
assert.ok(reloaded.items && reloaded.players, 'restrictions persist with both player and item maps');
fs.rmSync(root,{recursive:true,force:true});
console.log('PASS player and item blocklist, expiry and scoped rule tests');
